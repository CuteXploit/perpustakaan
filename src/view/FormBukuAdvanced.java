    private void tblBukuMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblBukuMouseClicked
int baris = tblBuku.getSelectedRow();
if (baris != -1) {
    // Memindahkan data dari tabel ke text field
    txtId.setText(tblBuku.getValueAt(baris, 0).toString());
    txtJudul.setText(tblBuku.getValueAt(baris, 1).toString());
    txtPenulis.setText(tblBuku.getValueAt(baris, 2).toString());
    txtTahun.setText(tblBuku.getValueAt(baris, 3).toString());
    txtStok.setText(tblBuku.getValueAt(baris, 4).toString());
    
    // Kunci kolom ID agar tidak bisa diedit karena merupakan Primary Key
    txtId.setEnabled(false);
}        // TODO add your handling code here:
    }//GEN-LAST:event_tblBukuMouseClicked

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
try {
    if (txtId.getText().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pilih dulu data buku yang ingin diedit dari tabel!");
        return;
    }
    
    int id = Integer.parseInt(txtId.getText());
    int stokBaru = Integer.parseInt(txtStok.getText());
    
    // Panggil fungsi update dari controller-mu
    controller.updateStok(id, stokBaru);
    
    // Refresh & Bersihkan Form
    tampilkanDataTabel();
    
    txtId.setText("");
    txtJudul.setText("");
    txtPenulis.setText("");
    txtTahun.setText("");
    txtStok.setText("");
    txtId.setEnabled(true);
    
    javax.swing.JOptionPane.showMessageDialog(this, "Stok buku berhasil diperbarui!");
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Stok harus berupa angka!");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnEditActionPerformed

