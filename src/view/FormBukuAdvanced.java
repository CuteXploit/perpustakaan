    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
try {
    // 1. Ambil data dari masing-masing JTextField Form
    int id = Integer.parseInt(txtId.getText());
    String judul = txtJudul.getText();
    String penulis = txtPenulis.getText();
    int tahun = Integer.parseInt(txtTahun.getText());
    int stok = Integer.parseInt(txtStok.getText());

    // 2. Bungkus ke dalam objek Model Buku
    Buku bukuBaru = new Buku();
    bukuBaru.setId(id);
    bukuBaru.setJudul(judul);
    bukuBaru.setPenulis(penulis);
    bukuBaru.setTahun(tahun);
    bukuBaru.setStok(stok);

    // 3. Panggil method insert dari controller-mu
    controller.tambahBuku(bukuBaru);

    // 4. Refresh tabel agar data baru langsung muncul
    tampilkanDataTabel();
    
    // 5. MANUAL RESET FORM (Menggantikan baris 319 yang error)
    txtId.setText("");
    txtJudul.setText("");
    txtPenulis.setText("");
    txtTahun.setText("");
    txtStok.setText("");
    txtId.setEnabled(true);
    txtId.requestFocus();
    
    javax.swing.JOptionPane.showMessageDialog(this, "Data buku berhasil disimpan!");
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "ID, Tahun, dan Stok harus berupa angka!");
}
    }//GEN-LAST:event_btnSimpanActionPerformed

