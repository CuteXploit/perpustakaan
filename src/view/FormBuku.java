    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
try {
    int id = Integer.parseInt(txtId.getText());
    int stokBaru = Integer.parseInt(txtStok.getText());

    controller.updateStok(id, stokBaru);
    JOptionPane.showMessageDialog(this, "Data berhasil diupdate!");
    tampilkanDataTabel();
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Mohon masukkan angka yang valid!");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
try {

        Buku buku = new Buku();

        buku.setId(Integer.parseInt(txtId.getText()));
        buku.setJudul(txtJudul.getText());
        buku.setPenulis(txtPenulis.getText());
        buku.setTahun(Integer.parseInt(txtTahun.getText()));
        buku.setStok(Integer.parseInt(txtStok.getText()));

        controller.tambahBuku(buku);

        JOptionPane.showMessageDialog(this,
                "Data berhasil disimpan!");

        tampilkanDataTabel();

        txtId.setText("");
        txtJudul.setText("");
        txtPenulis.setText("");
        txtTahun.setText("");
        txtStok.setText("");

        txtId.requestFocus();

    } catch (HeadlessException | NumberFormatException e) {

        JOptionPane.showMessageDialog(this, "Mohon masukkan angka yang valid!");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

