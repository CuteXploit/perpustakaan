    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
 if (txtId.getText().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Masukkan ID yang ingin dihapus!");

        return;
    }

    int id = Integer.parseInt(txtId.getText());

    controller.hapusBuku(id);

    JOptionPane.showMessageDialog(this,
            "Data berhasil dihapus!");

    tampilkanDataTabel();
          // TODO add your handling code here:
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnSimpanMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnSimpanMouseClicked
int baris = tabelBuku.getSelectedRow();
txtId.setText(tabelBuku.getValueAt(baris, 0).toString());
txtJudul.setText(tabelBuku.getValueAt(baris, 1).toString());
txtPenulis.setText(tabelBuku.getValueAt(baris, 2).toString());
txtTahun.setText(tabelBuku.getValueAt(baris, 3).toString());
txtStok.setText(tabelBuku.getValueAt(baris, 4).toString());

txtId.setEnabled(false); // Mengunci ID agar tidak bisa diubah saat diedit
   // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanMouseClicked

